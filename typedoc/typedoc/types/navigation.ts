/** Публичная навигация по декларациям и эффективным полям справочника TypeDoc. */
export interface TypeDocNavigationHandle {
  /**
  Прокручивает существующую цель в том же Document стандартным методом Element.

  @param declaration - Имя декларации из TypeDocDocument.
  @param path - Последовательность имён вложенных полей; пустой путь означает саму декларацию.
  @returns `true`, когда цель существует в текущей модели и получила прокрутку;
  `false`, когда декларация или путь отсутствуют, в том числе после dispose TypeDoc.
  */
  navigate(declaration: string, path: readonly string[]): boolean

  /**
  Находит видимую декларацию или поле без изменения прокрутки.

  @param viewport - Прокручиваемая область текущего Document, относительно которой
  проверяется пересечение прямоугольников по обеим осям.
  @returns Наиболее вложенный путь секции, пересекающей верхнюю границу viewport.
  Частично видимая секция участвует. Если верхняя граница не попала в секцию,
  возвращается первое видимое заглавие, а при совпадении — наиболее вложенное поле.
  Нулевые прямоугольники и цели из другого Document не участвуют; при отсутствии
  видимой секции возвращается `null`.
  */
  locate(viewport: Element): Readonly<{declaration: string; path: readonly string[]}> | null
}
